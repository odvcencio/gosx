type roomRateWindow struct {
	events []time.Time
}

// Room owns the server-authoritative scene and its synchronized CRDT document.
// Pointer and selection state is ephemeral; model placement and lighting are
// written to the document and reach peers through its watcher.
type Room struct {
	ID  string
	Hub *hub.Hub

	doc          *scene3d.Doc
	mu           sync.RWMutex
	props        scene.Props
	initialProps scene.Props
	objects      map[string]tabletopObject
	palette      map[string]string
	selected     map[string]string
	visitors     map[string]struct{}
	pointers     map[string]visitorPointer
	ptrSlots     map[string]int
	rates        map[string]map[string]*roomRateWindow
	lighting     string
	nextID       uint64
	lastUse      time.Time
	revision     atomic.Uint64
}

// RoomManager bounds in-memory private rooms and retires rooms that have no
// visitors and have been inactive for the configured interval.
type RoomManager struct {
	mu       sync.Mutex
	rooms    map[string]*Room
	maxRooms int
	idle     time.Duration
	newID    func() (string, error)
}

func NewRoomManager() *RoomManager {
	return &RoomManager{rooms: make(map[string]*Room), maxRooms: maxTabletopRooms, idle: tabletopRoomIdle, newID: randomRoomID}
}

// StartRoomJanitor deletes inactive rooms every minute until ctx is canceled.
func StartRoomJanitor(ctx context.Context) {
	if ctx == nil {
		ctx = context.Background()
	}
	go func() {
		ticker := time.NewTicker(time.Minute)
		defer ticker.Stop()
		for {
			select {
			case now := <-ticker.C:
				Rooms.Sweep(now)
			case <-ctx.Done():
				return
			}
		}
	}()
}

// ServeWebSocket resolves a room from the query string and serves its hub.
func ServeWebSocket(w http.ResponseWriter, req *http.Request) {
	if !validTabletopWebSocketRequest(req) {
		http.Error(w, "A valid same-origin WebSocket upgrade is required.", http.StatusBadRequest)
		return
	}
	room, err := Rooms.GetOrCreate(req.URL.Query().Get("room"), time.Now())
	if err != nil {
		http.Error(w, "This tabletop room is unavailable.", http.StatusNotFound)
		return
	}
	room.Hub.ServeHTTP(w, req)
}

func validTabletopWebSocketRequest(req *http.Request) bool {
	if req == nil || req.URL == nil || req.Method != http.MethodGet || !websocket.IsWebSocketUpgrade(req) {
		return false
	}
	if req.Header.Get("Sec-WebSocket-Version") != "13" {
		return false
	}
	key, err := base64.StdEncoding.DecodeString(req.Header.Get("Sec-WebSocket-Key"))
	if err != nil || len(key) != 16 {
		return false
	}
	origin := req.Header.Get("Origin")
	return origin != "" && (origin == "http://"+req.Host || origin == "https://"+req.Host)
}

// NewPrivateRoomID returns an unpredictable room URL without reserving a
// room. A page view alone must not consume one of the server's bounded slots.
func (m *RoomManager) NewPrivateRoomID() (string, error) {
	for attempt := 0; attempt < 8; attempt++ {
		id, err := m.newID()
		if err != nil {
			return "", err
		}
		if !validTabletopRoomID(id) {
			return "", ErrInvalidRoomID
		}
		m.mu.Lock()
		_, exists := m.rooms[id]
		m.mu.Unlock()
		if !exists {
			return id, nil
		}
	}
	return "", fmt.Errorf("tabletop: could not generate an unused room identifier")
}

// GetOrCreate returns the named room, refreshing its idle deadline, or creates
// it if the identifier is valid and the active-room cap has room.
func (m *RoomManager) GetOrCreate(id string, now time.Time) (*Room, error) {
	id = strings.TrimSpace(id)
	if !validTabletopRoomID(id) {
		return nil, ErrInvalidRoomID
	}
	m.mu.Lock()
	defer m.mu.Unlock()
	if room := m.rooms[id]; room != nil {
		room.touch(now)
		return room, nil
	}
	if len(m.rooms) >= m.maxRooms {
		return nil, ErrRoomLimit
	}
	room := newTabletopRoom(id, now)
	m.rooms[id] = room
	return room, nil
}

// GetForPage returns an active room or a temporary initial scene for a room
// link that has not connected yet. It never reserves a manager slot for a
// normal HTTP page request; the WebSocket handler creates the room after
// validating the upgrade request.
func (m *RoomManager) GetForPage(id string, now time.Time) (*Room, bool, error) {
	id = strings.TrimSpace(id)
	if !validTabletopRoomID(id) {
		return nil, false, ErrInvalidRoomID
	}
	m.mu.Lock()
	if room := m.rooms[id]; room != nil {
		room.touch(now)
		m.mu.Unlock()
		return room, true, nil
	}
	if len(m.rooms) >= m.maxRooms {
		m.mu.Unlock()
		return nil, false, ErrRoomLimit
	}
	m.mu.Unlock()
	return newTabletopRoom(id, now), false, nil
}

// Sweep removes rooms that exceeded the idle period and have no connected
// visitors. It returns the number of deleted rooms.
func (m *RoomManager) Sweep(now time.Time) int {
	m.mu.Lock()
	defer m.mu.Unlock()
	removed := 0
	for id, room := range m.rooms {
		if room.Hub.ClientCount() != 0 || now.Sub(room.lastUsed()) < m.idle {
			continue
		}
		delete(m.rooms, id)
		removed++
	}
	return removed
}

func (m *RoomManager) Count() int {
	m.mu.Lock()
	defer m.mu.Unlock()
	return len(m.rooms)
}

func randomRoomID() (string, error) {
	var raw [8]byte
	if _, err := rand.Read(raw[:]); err != nil {
		return "", err
	}
	return hex.EncodeToString(raw[:]), nil
}

func validTabletopRoomID(id string) bool {
	if len(id) != 16 {
		return false
	}
	for _, c := range id {
		if !(c >= '0' && c <= '9' || c >= 'a' && c <= 'f') {
			return false
		}
	}
	return true
}

func newTabletopRoom(id string, now time.Time) *Room {
	h := hub.New("tabletop-" + id)
	h.RequireOrigin = true
	h.MaxClients = maxTabletopVisitors
	h.MaxMessagesPerSecond = 30
	h.MaxMessageBurst = 60
	document := crdt.NewDoc()
	sceneDoc, err := scene3d.Bind(document, "tabletop")
	if err != nil {
		panic(err)
	}
	r := &Room{
		ID: id, Hub: h, doc: sceneDoc,
		objects:  make(map[string]tabletopObject),
		palette:  make(map[string]string),
		selected: make(map[string]string),
		visitors: make(map[string]struct{}),
		pointers: make(map[string]visitorPointer),
		rates:    make(map[string]map[string]*roomRateWindow),
		ptrSlots: make(map[string]int),
		lighting: "softbox", lastUse: now,
	}
	r.seedObjectsLocked()
	r.props = r.scenePropsLocked()
	r.initialProps = r.props
	seedCommands := scene.DiffPropsCommands(scene.Props{}, r.props)
	if _, err := r.doc.Apply(seedCommands, "seed tabletop"); err != nil {
		panic(err)
	}
	r.doc.Watch(func(commands []scene.Command) {
		if len(commands) == 0 {
			return
		}
		// Command bindings keep only the latest event while a renderer is
		// mounting, so publish the current diff from the room's original scene.
		go r.broadcastSceneSnapshot()
	})
	r.Hub.SetBinaryAuthorizer(func(_ *hub.Client, _ string) bool { return false })
	r.Hub.SyncDoc("scene", r.doc.Doc())
	r.installHandlers()
	return r
}

func (r *Room) installHandlers() {
	r.Hub.On("join", func(ctx *hub.Context) {
		now := time.Now()
		if !r.addVisitor(ctx.Client.ID, now) {
			return
		}
		r.sendSceneSnapshot(ctx.Client.ID)
		r.broadcastPresence()
		r.sendMetrics(ctx.Client.ID)
	})
	r.Hub.On("leave", func(ctx *hub.Context) {
		r.removeVisitor(ctx.Client.ID, time.Now())
		r.broadcastPresence()
		r.broadcastSceneSnapshot()
	})
	r.Hub.On("palette", func(ctx *hub.Context) {
		var kind string
		if json.Unmarshal(ctx.Data, &kind) != nil || !knownTabletopKind(kind) || !r.allow(ctx.Client.ID, "edit", time.Now(), 20) {
			return
		}
		r.mu.Lock()
		r.palette[ctx.Client.ID] = kind
		r.touchLocked(time.Now())
		r.mu.Unlock()
	})
	r.Hub.On("lighting", func(ctx *hub.Context) {
		var preset string
		if json.Unmarshal(ctx.Data, &preset) != nil || !knownLightingPreset(preset) || !r.allow(ctx.Client.ID, "edit", time.Now(), 20) {
			return
		}
		r.mu.Lock()
		previous := r.props.SceneIR()
		r.lighting = preset
		commands, err := r.applyPropsLocked(previous, "change tabletop light")
		r.mu.Unlock()
		if err == nil && len(commands) > 0 {
			r.sendMetrics("")
		}
	})
	r.Hub.On("scene:pick", func(ctx *hub.Context) {
		if !r.allow(ctx.Client.ID, "edit", time.Now(), 20) {
			return
		}
		var payload struct {
			Input struct {
				Type     string  `json:"type"`
				TargetID string  `json:"targetID"`
				WorldX   float64 `json:"worldX"`
				WorldZ   float64 `json:"worldZ"`
			} `json:"input"`
		}
		if json.Unmarshal(ctx.Data, &payload) != nil || payload.Input.Type != "select" {
			return
		}
		if payload.Input.TargetID == "tabletop-surface" {
			if r.placeAt(ctx.Client.ID, payload.Input.WorldX, payload.Input.WorldZ, time.Now()) == nil {
				r.sendMetrics("")
				r.sendSelection(ctx.Client.ID)
			}
			return
		}
		r.mu.Lock()
		if _, ok := r.objects[payload.Input.TargetID]; ok {
			r.selected[ctx.Client.ID] = payload.Input.TargetID
		}
		r.touchLocked(time.Now())
		r.mu.Unlock()
		r.sendMetrics("")
		r.sendSelection(ctx.Client.ID)
	})
	r.Hub.On("action", func(ctx *hub.Context) {
		var action string
		if json.Unmarshal(ctx.Data, &action) != nil || !r.allow(ctx.Client.ID, "edit", time.Now(), 20) {
			return
		}
		r.mutateSelection(ctx.Client.ID, action, time.Now())
	})
	r.Hub.On("object:rotate", func(ctx *hub.Context) {
		if r.allow(ctx.Client.ID, "edit", time.Now(), 20) {
			r.mutateSelection(ctx.Client.ID, "rotate", time.Now())
		}
	})
	r.Hub.On("object:remove", func(ctx *hub.Context) {
		if r.allow(ctx.Client.ID, "edit", time.Now(), 20) {
			r.mutateSelection(ctx.Client.ID, "remove", time.Now())
		}
	})
	r.Hub.On("presence:pointer", func(ctx *hub.Context) {
		if !r.allow(ctx.Client.ID, "pointer", time.Now(), 15) {
			return
		}
		var point visitorPointer
		if json.Unmarshal(ctx.Data, &point) != nil || !finite(point.X) || !finite(point.Y) || point.X < 0 || point.X > 1 || point.Y < 0 || point.Y > 1 {
			return
		}
		r.mu.Lock()
		if _, joined := r.visitors[ctx.Client.ID]; !joined {
			r.mu.Unlock()
			return
		}
		point.Color = visitorColor(ctx.Client.ID)
		point.WorldX, point.WorldZ = pointerWorldPosition(point.X, point.Y)
		r.pointers[ctx.Client.ID] = point
		commands := r.sceneSnapshotCommandsLocked(r.scenePropsWithPointersLocked())
		revision := r.revision.Add(1)
		r.touchLocked(time.Now())
		r.mu.Unlock()
		r.Hub.Broadcast("scene:update", scene.MountCommandBatch{Revision: revision, Commands: commands})
	})
	r.Hub.On("room:ping", func(ctx *hub.Context) {
		r.Hub.Send(ctx.Client.ID, "room:pong", json.RawMessage(ctx.Data))
	})
}

func (r *Room) seedObjectsLocked() {
	r.objects["prop-ceramic"] = tabletopObject{ID: "prop-ceramic", Kind: "ceramic", X: -0.78, Z: 0.16}
	r.objects["prop-brass"] = tabletopObject{ID: "prop-brass", Kind: "brass", X: 0.82, Z: 0.08, RotationY: 0.45}
	r.objects["prop-plant"] = tabletopObject{ID: "prop-plant", Kind: "plant", X: -1.12, Z: -0.82}
	r.objects["prop-book"] = tabletopObject{ID: "prop-book", Kind: "book", X: -0.95, Z: 1.05, RotationY: 0.2}
	r.objects["prop-candle"] = tabletopObject{ID: "prop-candle", Kind: "candle", X: 0.45, Z: 0.55}
	r.objects["prop-orb"] = tabletopObject{ID: "prop-orb", Kind: "orb", X: 1.5, Z: -1.0}
	r.nextID = uint64(len(r.objects))
}

func (r *Room) Props() scene.Props {
	r.mu.RLock()
	defer r.mu.RUnlock()
	return r.scenePropsWithPointersLocked()
}

// RoomMetrics is a server-renderable snapshot of room presence, scene state,
// and the serialized CRDT document size.
type RoomMetrics struct {
	Visitors      int
	Objects       int
	DocumentBytes int
	Lighting      string
}

func (r *Room) Metrics() RoomMetrics {
	document, err := r.doc.Doc().Save()
	if err != nil {
		document = nil
	}
	r.mu.RLock()
	defer r.mu.RUnlock()
	return RoomMetrics{Visitors: len(r.visitors), Objects: len(r.objects), DocumentBytes: len(document), Lighting: r.lighting}
}

