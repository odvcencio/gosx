func knownTabletopKind(kind string) bool {
	_, ok := tabletopKinds[kind]
	return ok
}

// ValidatePlacement is the server-side admission rule used before a model is
// written to the shared document.
func ValidatePlacement(kind string, x, z float64, currentObjects int) error {
	if !knownTabletopKind(kind) {
		return ErrInvalidKind
	}
	if !finite(x) || !finite(z) || math.Hypot(x, z) > tabletopSurfaceEdge {
		return ErrOutOfBounds
	}
	if currentObjects >= maxTabletopObjects {
		return ErrObjectLimit
	}
	return nil
}

func finite(value float64) bool { return !math.IsNaN(value) && !math.IsInf(value, 0) }

func (r *Room) addVisitor(clientID string, now time.Time) bool {
	r.mu.Lock()
	defer r.mu.Unlock()
	if _, ok := r.visitors[clientID]; ok {
		r.touchLocked(now)
		return true
	}
	if len(r.visitors) >= maxTabletopVisitors {
		return false
	}
	used := make(map[int]struct{}, len(r.ptrSlots))
	for _, slot := range r.ptrSlots {
		used[slot] = struct{}{}
	}
	for slot := 0; slot < maxTabletopVisitors; slot++ {
		if _, occupied := used[slot]; !occupied {
			r.ptrSlots[clientID] = slot
			break
		}
	}
	r.visitors[clientID] = struct{}{}
	r.palette[clientID] = "ceramic"
	r.touchLocked(now)
	return true
}

func (r *Room) removeVisitor(clientID string, now time.Time) {
	r.mu.Lock()
	delete(r.visitors, clientID)
	delete(r.pointers, clientID)
	delete(r.selected, clientID)
	delete(r.palette, clientID)
	delete(r.ptrSlots, clientID)
	delete(r.rates, clientID)
	r.touchLocked(now)
	r.mu.Unlock()
}

func (r *Room) placeAt(clientID string, x, z float64, now time.Time) error {
	r.mu.Lock()
	defer r.mu.Unlock()
	if _, joined := r.visitors[clientID]; !joined {
		return errors.New("tabletop: visitor is not in this room")
	}
	kind := r.palette[clientID]
	if err := ValidatePlacement(kind, x, z, len(r.objects)); err != nil {
		return err
	}
	previous := r.props.SceneIR()
	r.nextID++
	id := fmt.Sprintf("object-%03d", r.nextID)
	r.objects[id] = tabletopObject{ID: id, Kind: kind, X: x, Z: z}
	if _, err := r.applyPropsLocked(previous, "place tabletop object"); err != nil {
		delete(r.objects, id)
		return err
	}
	r.selected[clientID] = id
	r.touchLocked(now)
	return nil
}

func (r *Room) mutateSelection(clientID, action string, now time.Time) {
	r.mu.Lock()
	id := r.selected[clientID]
	object, exists := r.objects[id]
	if !exists {
		r.mu.Unlock()
		return
	}
	previous := r.props.SceneIR()
	clearedSelections := make([]string, 0)
	switch action {
	case "rotate":
		object.RotationY += math.Pi / 2
		r.objects[id] = object
	case "remove":
		delete(r.objects, id)
		delete(r.selected, clientID)
		for visitor, selected := range r.selected {
			if selected == id {
				delete(r.selected, visitor)
				clearedSelections = append(clearedSelections, visitor)
			}
		}
	default:
		r.mu.Unlock()
		return
	}
	_, err := r.applyPropsLocked(previous, "edit tabletop object")
	if err != nil {
		r.objects[id] = object
	}
	r.touchLocked(now)
	r.mu.Unlock()
	if err == nil {
		r.sendMetrics("")
		for _, visitor := range clearedSelections {
			r.sendSelection(visitor)
		}
	} else {
		r.sendSelection(clientID)
	}
}

func (r *Room) applyPropsLocked(previous scene.SceneIR, reason string) ([]scene.Command, error) {
	next := r.scenePropsLocked()
	commands, _, err := r.doc.DiffScene(previous, next.SceneIR(), reason)
	if err == nil {
		r.props = next
	}
	return commands, err
}

func (r *Room) allow(clientID, category string, now time.Time, maxPerSecond int) bool {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.touchLocked(now)
	byKind := r.rates[clientID]
	if byKind == nil {
		byKind = make(map[string]*roomRateWindow)
		r.rates[clientID] = byKind
	}
	window := byKind[category]
	if window == nil {
		window = &roomRateWindow{}
		byKind[category] = window
	}
	cutoff := now.Add(-time.Second)
	first := 0
	for first < len(window.events) && !window.events[first].After(cutoff) {
		first++
	}
	window.events = append(window.events[:0], window.events[first:]...)
	if len(window.events) >= maxPerSecond {
		return false
	}
	window.events = append(window.events, now)
	return true
}

func (r *Room) addVisitorCount() int {
	r.mu.RLock()
	defer r.mu.RUnlock()
	return len(r.visitors)
}

func (r *Room) sendMetrics(clientID string) {
	data, err := r.doc.Doc().Save()
	if err != nil {
		return
	}
	r.mu.RLock()
	count := len(r.visitors)
	objects := len(r.objects)
	lighting := r.lighting
	r.mu.RUnlock()
	metrics := map[string]any{"visitors": count, "objects": objects, "lighting": lighting, "documentBytes": len(data)}
	if clientID == "" {
		r.Hub.Broadcast("room:ui", metrics)
	} else {
		r.Hub.Send(clientID, "room:ui", metrics)
		r.sendSelection(clientID)
	}
}

func (r *Room) sendSelection(clientID string) {
	r.mu.RLock()
	selection := r.selected[clientID]
	r.mu.RUnlock()
	r.Hub.Send(clientID, "room:selected", selection)
}

func (r *Room) broadcastPresence() {
	r.Hub.Broadcast("room:presence", map[string]any{"visitors": r.addVisitorCount()})
	r.sendMetrics("")
}

func (r *Room) touch(now time.Time) {
	r.mu.Lock()
	r.touchLocked(now)
	r.mu.Unlock()
}

func (r *Room) touchLocked(now time.Time) { r.lastUse = now }

func (r *Room) lastUsed() time.Time {
	r.mu.RLock()
	defer r.mu.RUnlock()
	return r.lastUse
}

func visitorColor(id string) string {
	colors := [...]string{"#8bd5ca", "#c6a0f6", "#f5a97f", "#91d7e3", "#ed8796", "#a6da95", "#f4dbd6", "#eed49f"}
	var sum uint32
	for _, c := range id {
		sum = sum*31 + uint32(c)
	}
	return colors[int(sum)%len(colors)]
}
