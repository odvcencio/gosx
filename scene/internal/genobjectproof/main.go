//go:build ignore

// Generate the typed ObjectIR equality proof from its authored Go declarations.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path"
	"reflect"
	"sort"
	"strconv"
	"strings"
)

type field struct {
	name string
	typ  ast.Expr
	tag  reflect.StructTag
}

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	fset := token.NewFileSet()
	source, err := parser.ParseFile(fset, "scene_ir.go", nil, 0)
	if err != nil {
		return err
	}
	patches, err := parser.ParseFile(fset, "diff.go", nil, 0)
	if err != nil {
		return err
	}
	textures, err := parser.ParseFile(fset, "texture_contract.go", nil, 0)
	if err != nil {
		return err
	}
	proofNames := []string{"MaterialTextureDescriptors", "TextureDescriptor"}
	proofs := map[string][]field{}
	for _, name := range proofNames {
		proofs[name] = fields(textures, name)
		if len(proofs[name]) == 0 {
			return fmt.Errorf("missing texture declaration %s", name)
		}
	}
	scalarTypes := map[string]ast.Expr{}
	for _, decl := range textures.Decls {
		if g, ok := decl.(*ast.GenDecl); ok {
			for _, spec := range g.Specs {
				if t, ok := spec.(*ast.TypeSpec); ok {
					scalarTypes[t.Name.Name] = t.Type
				}
			}
		}
	}
	objects := fields(source, "ObjectIR")
	transforms := fields(patches, "TransformPatch")
	states := fields(patches, "ObjectStatePatch")
	if len(objects) == 0 || len(transforms) == 0 || len(states) == 0 {
		return fmt.Errorf("missing object or patch declaration")
	}
	transformNames, stateNames := map[string]bool{}, map[string]bool{}
	for _, f := range transforms {
		transformNames[f.name] = true
	}
	for _, f := range states {
		stateNames[f.name] = true
	}
	var groups [3][]field
	for _, f := range objects {
		group := 2
		if transformNames[f.name] {
			group = 1
		} else if stateNames[f.name] {
			group = 0
		}
		groups[group] = append(groups[group], f)
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go generate; DO NOT EDIT.\n\npackage scene")
	usedPackages := map[string]bool{}
	allFields := append([]field(nil), objects...)
	for _, name := range proofNames {
		allFields = append(allFields, proofs[name]...)
	}
	for _, f := range allFields {
		ast.Inspect(f.typ, func(node ast.Node) bool {
			if s, ok := node.(*ast.SelectorExpr); ok {
				if p, ok := s.X.(*ast.Ident); ok {
					usedPackages[p.Name] = true
				}
			}
			return true
		})
	}
	imports := []string{`"reflect"`}
	for _, imp := range append(append([]*ast.ImportSpec(nil), source.Imports...), textures.Imports...) {
		value, err := strconv.Unquote(imp.Path.Value)
		if err != nil {
			return err
		}
		name := path.Base(value)
		if imp.Name != nil {
			name = imp.Name.Name
		}
		if usedPackages[name] {
			entry := imp.Path.Value
			if imp.Name != nil {
				entry = name + " " + entry
			}
			imports = append(imports, entry)
			delete(usedPackages, name)
		}
	}
	if len(usedPackages) != 0 {
		return fmt.Errorf("unresolved field type imports: %v", usedPackages)
	}
	sort.Strings(imports)
	if len(imports) == 1 {
		fmt.Fprintln(&out, "\nimport "+imports[0])
	} else {
		fmt.Fprintln(&out, "\nimport (")
		for _, imp := range imports {
			fmt.Fprintln(&out, imp)
		}
		fmt.Fprintln(&out, ")")
	}
	fmt.Fprintln(&out, "\n// Validate names and types lazily before using generated field accesses.\n// Nested texture declarations participate so stale proofs fail closed.\nfunc objectProofSchemaMatches() bool {")
	fmt.Fprint(&out, "return objectProofSchemaMatchesType(reflect.TypeFor[ObjectIR]())")
	for _, name := range proofNames {
		fmt.Fprintf(&out, " && %sProofSchemaMatchesType(reflect.TypeFor[%s]())", lowerFirst(name), name)
	}
	// A named scalar can keep its Go type identity while changing its underlying
	// kind. Guard that kind as well before using a generated scalar comparison.
	var names []string
	for name, typ := range scalarTypes {
		if scalarDifference(underlyingType(typ, scalarTypes), "a", "b") != "" {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	fmt.Fprint(&out, " && textureScalarProofSchemaMatches(")
	for _, name := range names {
		fmt.Fprintf(&out, "reflect.TypeFor[%s](),", name)
	}
	fmt.Fprintln(&out, ")\n}")
	fmt.Fprintln(&out, "\nfunc textureScalarProofSchemaMatches(types ...reflect.Type) bool {\nexpected := [...]reflect.Kind{")
	for _, name := range names {
		var typ bytes.Buffer
		if err := format.Node(&typ, fset, underlyingType(scalarTypes[name], scalarTypes)); err != nil {
			return err
		}
		fmt.Fprintf(&out, "reflect.TypeFor[%s]().Kind(),\n", typ.String())
	}
	fmt.Fprintln(&out, `}
 if len(types) != len(expected) { return false }
 for i, typ := range types { if typ == nil || typ.Kind() != expected[i] { return false } }
 return true
 }`)

	writeSchema(&out, fset, "object", objects)
	for _, name := range proofNames {
		writeSchema(&out, fset, lowerFirst(name), proofs[name])
	}
	fmt.Fprintln(&out, `
// Like provenJSONEqual, false means not proven; callers retain the JSON fallback.
// Patch proofs omit only fields their typed patch replaces.
func provenObjectFieldsEqual(a, b *ObjectIR, omitted objectProofOmissions) bool {`)
	for i, group := range groups {
		if i == 0 {
			fmt.Fprintln(&out, "if omitted & objectProofOmitState == 0 {")
		}
		if i == 1 {
			fmt.Fprintln(&out, "if omitted & objectProofOmitTransform == 0 {")
		}
		for _, f := range group {
			compare(&out, f, proofs, scalarTypes)
		}
		if i < 2 {
			fmt.Fprintln(&out, "}")
		}
	}
	fmt.Fprintln(&out, "return true\n}")
	for _, name := range proofNames {
		fmt.Fprintf(&out, "\nfunc proven%sEqual(a, b *%s) bool {\n", name, name)
		for _, f := range proofs[name] {
			compare(&out, f, proofs, scalarTypes)
		}
		fmt.Fprintln(&out, "return true\n}")
	}
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile("diff_object_generated.go", formatted, 0644)
}

func lowerFirst(name string) string { return strings.ToLower(name[:1]) + name[1:] }

func writeSchema(out *bytes.Buffer, fset *token.FileSet, name string, fields []field) {
	fmt.Fprintf(out, "\nfunc %sProofSchemaMatchesType(t reflect.Type) bool {\n", name)
	fmt.Fprintln(out, `if t.Kind() != reflect.Struct || sceneRecordHasJSONMarshaler(t) { return false }
 fields := [...]struct { name string; typ reflect.Type; tag reflect.StructTag }{`)
	for _, f := range fields {
		var typ bytes.Buffer
		if err := format.Node(&typ, fset, f.typ); err != nil {
			panic(err)
		}
		fmt.Fprintf(out, "{%q, reflect.TypeFor[%s](), %q},\n", f.name, typ.String(), string(f.tag))
	}
	fmt.Fprintln(out, `}
 if t.NumField() != len(fields) { return false }
 for i, expected := range fields {
  actual := t.Field(i)
  if actual.Name != expected.name || actual.Type != expected.typ || actual.Tag != expected.tag { return false }
 }
 return true
}`)
}

func fields(file *ast.File, name string) []field {
	for _, decl := range file.Decls {
		g, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range g.Specs {
			t, ok := spec.(*ast.TypeSpec)
			if !ok || t.Name.Name != name {
				continue
			}
			s, ok := t.Type.(*ast.StructType)
			if !ok {
				panic("expected struct " + name)
			}
			var result []field
			for _, f := range s.Fields.List {
				if len(f.Names) == 0 {
					if name != "TransformPatch" && name != "ObjectStatePatch" {
						panic("embedded " + name + " fields require an explicit proof")
					}
					continue
				}
				for _, n := range f.Names {
					if n.Name == "_" {
						panic("blank " + name + " fields require an explicit proof")
					}
					var tag reflect.StructTag
					if f.Tag != nil {
						text, err := strconv.Unquote(f.Tag.Value)
						if err != nil {
							panic(err)
						}
						tag = reflect.StructTag(text)
					}
					result = append(result, field{name: n.Name, typ: f.Type, tag: tag})
				}
			}
			return result
		}
	}
	return nil
}

func scalarDifference(typ ast.Expr, left, right string) string {
	id, ok := typ.(*ast.Ident)
	if !ok {
		return ""
	}
	switch id.Name {
	case "bool", "string", "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64", "uintptr", "byte", "rune":
		return left + " != " + right
	case "float64":
		return "!provenFloatEqual(" + left + ", " + right + ")"
	case "float32":
		return "!provenFloatEqual(float64(" + left + "), float64(" + right + "))"
	}
	return ""
}

func underlyingType(typ ast.Expr, declarations map[string]ast.Expr) ast.Expr {
	for depth := 0; depth < len(declarations); depth++ {
		ident, ok := typ.(*ast.Ident)
		if !ok || declarations[ident.Name] == nil {
			break
		}
		typ = declarations[ident.Name]
	}
	return typ
}

func compare(out *bytes.Buffer, f field, proofs map[string][]field, scalarTypes map[string]ast.Expr) {
	a, b := "a."+f.name, "b."+f.name
	if typ, ok := f.typ.(*ast.Ident); ok && typ.Name == "AlphaCutoff" {
		for _, option := range strings.Split(f.tag.Get("json"), ",")[1:] {
			if option == "omitzero" {
				fmt.Fprintf(out, "if !provenAlphaCutoffFieldEqual(%s, %s) { return false }\n", a, b)
				return
			}
		}
	}
	if ident, ok := f.typ.(*ast.Ident); ok && proofs[ident.Name] != nil {
		fmt.Fprintf(out, "if !proven%sEqual(&%s, &%s) { return false }\n", ident.Name, a, b)
		return
	}
	// Named scalar fields have the same structural equality rule as their
	// underlying kind. Retain the existing reflective proof for other types.
	typ := underlyingType(f.typ, scalarTypes)
	if different := scalarDifference(typ, a, b); different != "" {
		fmt.Fprintf(out, "if %s { return false }\n", different)
		return
	}
	if ptr, ok := f.typ.(*ast.StarExpr); ok {
		if different := scalarDifference(ptr.X, "*"+a, "*"+b); different != "" {
			fmt.Fprintf(out, "if %s != nil || %s != nil {\n if %s == nil || %s == nil || %s { return false }\n}\n", a, b, a, b, different)
			return
		}
	}
	canBeNil := false
	switch typ := f.typ.(type) {
	case *ast.StarExpr, *ast.MapType, *ast.InterfaceType:
		canBeNil = true
	case *ast.ArrayType:
		canBeNil = typ.Len == nil
	}
	if canBeNil {
		fmt.Fprintf(out, "if %s != nil || %s != nil {\n", a, b)
	}
	fmt.Fprintf(out, "if !provenJSONEqual(reflect.ValueOf(&%s).Elem(), reflect.ValueOf(&%s).Elem()) { return false }\n", a, b)
	if canBeNil {
		fmt.Fprintln(out, "}")
	}
}
