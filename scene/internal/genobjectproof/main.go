//go:build ignore

// Generate the typed ObjectIR equality proof from its authored Go declarations.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path"
	"sort"
	"strconv"
)

type field struct {
	name string
	typ  ast.Expr
}

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	fset := token.NewFileSet()
	source, err := parser.ParseFile(fset, "scene_ir.go", nil, 0)
	if err != nil {
		return err
	}
	patches, err := parser.ParseFile(fset, "diff.go", nil, 0)
	if err != nil {
		return err
	}
	objects := fields(source, "ObjectIR")
	transforms := fields(patches, "TransformPatch")
	states := fields(patches, "ObjectStatePatch")
	if len(objects) == 0 || len(transforms) == 0 || len(states) == 0 {
		return fmt.Errorf("missing object or patch declaration")
	}
	transformNames, stateNames := map[string]bool{}, map[string]bool{}
	for _, f := range transforms {
		transformNames[f.name] = true
	}
	for _, f := range states {
		stateNames[f.name] = true
	}
	var groups [3][]field
	for _, f := range objects {
		group := 2
		if transformNames[f.name] {
			group = 1
		} else if stateNames[f.name] {
			group = 0
		}
		groups[group] = append(groups[group], f)
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go generate; DO NOT EDIT.\n\npackage scene")
	usedPackages := map[string]bool{}
	for _, f := range objects {
		ast.Inspect(f.typ, func(node ast.Node) bool {
			if s, ok := node.(*ast.SelectorExpr); ok {
				if p, ok := s.X.(*ast.Ident); ok {
					usedPackages[p.Name] = true
				}
			}
			return true
		})
	}
	imports := []string{`"reflect"`}
	for _, imp := range source.Imports {
		value, err := strconv.Unquote(imp.Path.Value)
		if err != nil {
			return err
		}
		name := path.Base(value)
		if imp.Name != nil {
			name = imp.Name.Name
		}
		if usedPackages[name] {
			entry := imp.Path.Value
			if imp.Name != nil {
				entry = name + " " + entry
			}
			imports = append(imports, entry)
			delete(usedPackages, name)
		}
	}
	if len(usedPackages) != 0 {
		return fmt.Errorf("unresolved field type imports: %v", usedPackages)
	}
	sort.Strings(imports)
	if len(imports) == 1 {
		fmt.Fprintln(&out, "\nimport "+imports[0])
	} else {
		fmt.Fprintln(&out, "\nimport (")
		for _, imp := range imports {
			fmt.Fprintln(&out, imp)
		}
		fmt.Fprintln(&out, ")")
	}
	fmt.Fprintln(&out, `
// Validate names and types lazily before using generated field accesses. A stale
// proof declines and leaves the reflective/reference comparison in control.
func objectProofSchemaMatches() bool {
 return objectProofSchemaMatchesType(reflect.TypeFor[ObjectIR]())
}

func objectProofSchemaMatchesType(t reflect.Type) bool {
 if t.Kind() != reflect.Struct { return false }
 fields := [...]struct { name string; typ reflect.Type }{`)
	for _, f := range objects {
		var typ bytes.Buffer
		if err := format.Node(&typ, fset, f.typ); err != nil {
			return err
		}
		fmt.Fprintf(&out, "{%q, reflect.TypeFor[%s]()},\n", f.name, typ.String())
	}
	fmt.Fprintln(&out, `}
 if t.NumField() != len(fields) { return false }
 for i, expected := range fields {
  actual := t.Field(i)
  if actual.Name != expected.name || actual.Type != expected.typ { return false }
 }
 return true
}`)
	fmt.Fprintln(&out, `
// Like provenJSONEqual, false means not proven; callers retain the JSON fallback.
// Patch proofs omit only fields their typed patch replaces.
func provenObjectFieldsEqual(a, b *ObjectIR, omitted objectProofOmissions) bool {`)
	for i, group := range groups {
		if i == 0 {
			fmt.Fprintln(&out, "if omitted & objectProofOmitState == 0 {")
		}
		if i == 1 {
			fmt.Fprintln(&out, "if omitted & objectProofOmitTransform == 0 {")
		}
		for _, f := range group {
			compare(&out, f)
		}
		if i < 2 {
			fmt.Fprintln(&out, "}")
		}
	}
	fmt.Fprintln(&out, "return true\n}")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile("diff_object_generated.go", formatted, 0644)
}

func fields(file *ast.File, name string) []field {
	for _, decl := range file.Decls {
		g, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range g.Specs {
			t, ok := spec.(*ast.TypeSpec)
			if !ok || t.Name.Name != name {
				continue
			}
			s, ok := t.Type.(*ast.StructType)
			if !ok {
				panic("expected struct " + name)
			}
			var result []field
			for _, f := range s.Fields.List {
				if len(f.Names) == 0 {
					if name == "ObjectIR" {
						panic("embedded ObjectIR fields require an explicit proof")
					}
					continue
				}
				for _, n := range f.Names {
					if n.Name == "_" {
						panic("blank ObjectIR fields require an explicit proof")
					}
					result = append(result, field{n.Name, f.Type})
				}
			}
			return result
		}
	}
	return nil
}

func scalarDifference(typ ast.Expr, left, right string) string {
	id, ok := typ.(*ast.Ident)
	if !ok {
		return ""
	}
	switch id.Name {
	case "bool", "string", "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64", "uintptr", "byte", "rune":
		return left + " != " + right
	case "float64":
		return "!provenFloatEqual(" + left + ", " + right + ")"
	case "float32":
		return "!provenFloatEqual(float64(" + left + "), float64(" + right + "))"
	}
	return ""
}

func compare(out *bytes.Buffer, f field) {
	a, b := "a."+f.name, "b."+f.name
	if different := scalarDifference(f.typ, a, b); different != "" {
		fmt.Fprintf(out, "if %s { return false }\n", different)
		return
	}
	if ptr, ok := f.typ.(*ast.StarExpr); ok {
		if different := scalarDifference(ptr.X, "*"+a, "*"+b); different != "" {
			fmt.Fprintf(out, "if %s != nil || %s != nil {\n if %s == nil || %s == nil || %s { return false }\n}\n", a, b, a, b, different)
			return
		}
	}
	canBeNil := false
	switch typ := f.typ.(type) {
	case *ast.StarExpr, *ast.MapType, *ast.InterfaceType:
		canBeNil = true
	case *ast.ArrayType:
		canBeNil = typ.Len == nil
	}
	if canBeNil {
		fmt.Fprintf(out, "if %s != nil || %s != nil {\n", a, b)
	}
	fmt.Fprintf(out, "if !provenJSONEqual(reflect.ValueOf(&%s).Elem(), reflect.ValueOf(&%s).Elem()) { return false }\n", a, b)
	if canBeNil {
		fmt.Fprintln(out, "}")
	}
}
