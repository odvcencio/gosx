// Command pkgmap writes docs/packages.md, the map of every importable GoSX
// package: its layer, its stability tier, what it does and whether it builds
// for js/wasm. It reads the package list from `go list` and the layer and tier
// of each package from scripts/pkgmap/layers.txt, so the page cannot drift from
// the tree.
//
//	go run ./scripts/pkgmap            # rewrite docs/packages.md
//	go run ./scripts/pkgmap --check    # exit 1 if docs/packages.md is stale
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

type rule struct {
	prefix string
	tree   bool
	layer  string
	tier   string
}

type pkg struct {
	Rel   string
	Doc   string
	Layer string
	Tier  string
	WASM  bool
}

type listed struct {
	ImportPath string
	Doc        string
	GoFiles    []string
	Module     *struct{ Path string }
	Error      *struct{ Err string }
}

type layerInfo struct{ name, title, rule string }

var layers = []layerInfo{
	{"foundations", "Foundations", "Imports no other GoSX layer."},
	{"kernels", "Kernels", "No hub, server or route."},
	{"scene", "Scene and compiler", "No server, route or hub."},
	{"web", "Web primitives", "No server or route."},
	{"server", "App server", "No game stack."},
	{"game", "Game stack", "May import any layer before it."},
	{"browser", "Browser side", "Builds for js/wasm. No root package, hub, net/http or parsers."},
	{"tools", "Tools", "CLI, desktop host, evidence and test packages. No library imports them."},
}

var tiers = map[string]bool{"stable": true, "experimental": true, "internal-use": true}

func main() {
	check := flag.Bool("check", false, "exit 1 if the output file is stale")
	root := flag.String("root", ".", "module root")
	out := flag.String("o", "docs/packages.md", "output file, relative to the root")
	flag.Parse()
	if err := run(*root, *out, *check); err != nil {
		fmt.Fprintln(os.Stderr, "pkgmap:", err)
		os.Exit(1)
	}
}

func run(root, out string, check bool) error {
	got, err := Render(root)
	if err != nil {
		return err
	}
	path := filepath.Join(root, out)
	if check {
		want, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(want, got) {
			return fmt.Errorf("%s is stale; run `go run ./scripts/pkgmap`", out)
		}
		return nil
	}
	return os.WriteFile(path, got, 0o644)
}

// Render returns the package map page for the module at root.
func Render(root string) ([]byte, error) {
	rules, err := readRules(filepath.Join(root, "scripts", "pkgmap", "layers.txt"))
	if err != nil {
		return nil, err
	}
	native, err := goList(root, nil)
	if err != nil {
		return nil, err
	}
	wasm, err := goList(root, []string{"GOOS=js", "GOARCH=wasm"})
	if err != nil {
		return nil, err
	}
	onWASM := map[string]bool{}
	for _, p := range wasm {
		if p.Error == nil && len(p.GoFiles) > 0 {
			onWASM[p.ImportPath] = true
		}
	}
	module := ""
	for _, p := range native {
		if p.Module != nil {
			module = p.Module.Path
			break
		}
	}
	var pkgs []pkg
	var unassigned []string
	for _, p := range native {
		if p.Error != nil || len(p.GoFiles) == 0 {
			continue
		}
		rel := "."
		if p.ImportPath != module {
			rel = strings.TrimPrefix(p.ImportPath, module+"/")
		}
		if skip(rel) {
			continue
		}
		r, ok := match(rules, rel)
		if !ok {
			unassigned = append(unassigned, rel)
			continue
		}
		pkgs = append(pkgs, pkg{Rel: rel, Doc: synopsis(p.Doc), Layer: r.layer, Tier: r.tier, WASM: onWASM[p.ImportPath]})
	}
	if len(unassigned) > 0 {
		return nil, fmt.Errorf("no row in scripts/pkgmap/layers.txt for: %s", strings.Join(unassigned, ", "))
	}
	sort.Slice(pkgs, func(i, j int) bool { return pkgs[i].Rel < pkgs[j].Rel })
	return page(module, pkgs), nil
}

// skip drops packages that are not importable library surface.
func skip(rel string) bool {
	if rel == "internal" || strings.HasPrefix(rel, "internal/") || strings.Contains(rel, "/internal/") {
		return true
	}
	return strings.HasPrefix(rel, "examples/") || strings.Contains(rel, "testdata")
}

func page(module string, pkgs []pkg) []byte {
	var b strings.Builder
	b.WriteString("<!-- Generated by `go run ./scripts/pkgmap` from the package tree and scripts/pkgmap/layers.txt. Do not edit by hand. -->\n\n")
	b.WriteString("# Package map\n\n")
	b.WriteString("Every importable package in `" + module + "`, grouped by layer. The [guides index](README.md) points to the guide for each topic; [stability tiers](STABILITY.md) explains the tier column.\n\n")
	b.WriteString("## Layers and import direction\n\n")
	b.WriteString("Layers run from the bottom up. A package may import its own layer and the layers listed before it in this table, subject to the extra rule in the second column. Browser-side and tool packages are special cases. The rules are the target direction. A test enforces them only for the browser game packages (`game/deps_test.go`); other edges are checked by review.\n\n")
	b.WriteString("| Layer | Rule |\n|---|---|\n")
	for _, l := range layers {
		fmt.Fprintf(&b, "| %s | %s |\n", l.title, l.rule)
	}
	b.WriteString("\nFour nested modules keep heavy dependencies out of the core module: `editor`, `netplay/webrtc`, `game/teamai/arbiterrules` and `cmd/buildbootstrap`. See [MODULES.md](../MODULES.md).\n")
	for _, l := range layers {
		var rows []pkg
		for _, p := range pkgs {
			if p.Layer == l.name {
				rows = append(rows, p)
			}
		}
		if len(rows) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n## %s\n\n| Package | Tier | js/wasm | What it is |\n|---|---|---|---|\n", l.title)
		for _, p := range rows {
			w := "no"
			if p.WASM {
				w = "yes"
			}
			imp := "`" + p.Rel + "`"
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", imp, p.Tier, w, p.Doc)
		}
	}
	return []byte(b.String())
}

func synopsis(doc string) string {
	words := strings.Fields(doc)
	if len(words) > 2 && (words[0] == "Package" || words[0] == "Command") {
		words = words[2:]
		if len(words) > 0 && (words[0] == "is" || words[0] == "provides") {
			// keep the verb phrase readable: "is a server..." -> "A server..."
			if words[0] == "is" && len(words) > 1 {
				words = words[1:]
			}
		}
	}
	doc = strings.Join(words, " ")
	if doc == "" {
		return ""
	}
	doc = strings.ToUpper(doc[:1]) + doc[1:]
	return strings.ReplaceAll(doc, "|", "\\|")
}

func readRules(path string) ([]rule, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	known := map[string]bool{}
	for _, l := range layers {
		known[l.name] = true
	}
	var rules []rule
	sc := bufio.NewScanner(f)
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) != 3 || !known[fields[1]] || !tiers[fields[2]] {
			return nil, fmt.Errorf("%s:%d: want `path layer tier` with a known layer and tier", path, n)
		}
		r := rule{prefix: fields[0], layer: fields[1], tier: fields[2]}
		if strings.HasSuffix(r.prefix, "/...") {
			r.tree = true
			r.prefix = strings.TrimSuffix(r.prefix, "/...")
		}
		rules = append(rules, r)
	}
	return rules, sc.Err()
}

func match(rules []rule, rel string) (rule, bool) {
	best, found, bestLen := rule{}, false, -1
	for _, r := range rules {
		ok := rel == r.prefix || (r.tree && strings.HasPrefix(rel, r.prefix+"/"))
		if ok && len(r.prefix) > bestLen {
			best, found, bestLen = r, true, len(r.prefix)
		}
	}
	return best, found
}

func goList(root string, env []string) ([]listed, error) {
	cmd := exec.Command("go", "list", "-e", "-json=ImportPath,Doc,GoFiles,Module,Error", "./...")
	cmd.Dir = root
	cmd.Env = append(os.Environ(), append([]string{"GOWORK=off"}, env...)...)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list: %w: %s", err, stderr.String())
	}
	var pkgs []listed
	dec := json.NewDecoder(bytes.NewReader(out))
	for {
		var p listed
		if err := dec.Decode(&p); errors.Is(err, io.EOF) {
			break
		} else if err != nil {
			return nil, err
		}
		pkgs = append(pkgs, p)
	}
	return pkgs, nil
}
